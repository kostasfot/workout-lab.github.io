async function exercises(page: Page) {
  await page.goto('/#/progress?view=exercises')
  await expect(page.getByTestId('exercise-explorer')).toBeVisible()
}
async function choose(page: Page, name: string) {
  const selector = page.getByRole('combobox', { name: 'Άσκηση για ανάλυση', exact: true })
  const value = await selector.locator('option').filter({ hasText: `${name} ·` }).first().getAttribute('value')
  await selector.selectOption(value!)
}
async function layout(page: Page) {
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
  const bounds = await page.getByTestId('exercise-trend-chart').boundingBox()
  if (bounds) expect(bounds.width).toBeGreaterThan(220)
}

test('exercise explorer compares athletes, calculates meaningful records, and links charts to saved history', async ({ page }, info) => {
  await mockAccount(page, 'coach', true, { configureWorkspace: analyticsWorkspace })
  await exercises(page)
  await expect(page.getByTestId('target-attainment-anna')).toHaveText('77,8%')
  await expect(page.getByTestId('target-attainment-dimitra')).toHaveText('44,4%')
  await expect(page.getByTestId('set-completion-anna')).toHaveText('9 / 9')
  const records = page.getByRole('region', { name: 'Ρεκόρ Άννα', exact: true })
  await expect(records.getByText('7,5 kg / αλτήρα', { exact: true })).toBeVisible()
  await page.getByRole('combobox', { name: 'Βάρος σύγκρισης ρεκόρ' }).selectOption('6')
  await expect(records.getByText('12 επ.', { exact: true })).toBeVisible()
  const threshold = page.getByRole('spinbutton', { name: 'Ελάχιστος στόχος ρεκόρ' })
  await threshold.fill(''); await threshold.pressSequentially('12')
  await expect(threshold).toHaveValue('12')
  await expect(records.getByText('6 kg / αλτήρα', { exact: true })).toBeVisible()
  await page.getByRole('combobox', { name: 'Μέτρηση γραφήματος άσκησης' }).selectOption('value')
  await expect(page.getByRole('heading', { name: 'Μέση τιμή επαναλήψεων ανά ολοκληρωμένο σετ', exact: true })).toBeVisible()
  await layout(page)
  await page.screenshot({ path: info.outputPath('exercise-explorer.png'), fullPage: true })
  const point = page.getByTestId('exercise-trend-chart').getByRole('button', { name: /^Προβολή καταγραφής Άννα/ }).first()
  await point.focus(); await point.press('Enter')
  await expect(page.getByRole('dialog').getByRole('heading', { name: 'Προπόνηση 1', exact: true })).toBeVisible()
  await page.goBack()
  await expect(page.getByRole('combobox', { name: 'Βάρος σύγκρισης ρεκόρ' })).toHaveValue('6')
  await expect(page.getByRole('spinbutton', { name: 'Ελάχιστος στόχος ρεκόρ' })).toHaveValue('12')
})


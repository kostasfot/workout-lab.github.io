test('round consistency exposes changed loads and missing rounds instead of producing a misleading change', async ({ page }) => {
  const { remote } = await mockAccount(page, 'coach', true, { configureWorkspace: w => {
    analyticsWorkspace(w)
    const first = w.workouts[0], rows = allExpected(first).filter(r => r.movement.id === 'goblet')
    first.results[rows.find(r => r.athlete === 'anna' && r.round === 1)!.key].weight = 7.5
    delete first.results[rows.find(r => r.athlete === 'dimitra' && r.round === 2)!.key]
  } })
  await exercises(page)
  await page.getByRole('combobox', { name: 'Προπόνηση για συνέπεια γύρων' }).selectOption(remote.workouts[0].id)
  await expect(page.locator('.analytics-round-changes')).toContainText('Διαφορετικό βάρος μεταξύ γύρων')
  await expect(page.locator('.analytics-round-changes')).toContainText('Δεν έχουν ολοκληρωθεί όλοι οι γύροι')
  await expect(page.locator('.round-values')).toContainText('Χωρίς καταγραφή')
  await expect(page.locator('.round-values')).toContainText('7,5 kg')
  await layout(page)
})


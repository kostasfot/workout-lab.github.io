test('athletes cannot open management and removed membership ends online app access', async ({ page }) => {
  const { profiles, accountRequests } = await mockAccount(page, 'athlete')
  await expect(page.getByRole('link', { name: 'Διαχείριση', exact: true })).toHaveCount(0)
  await page.goto('/#/management'); await expect(page).toHaveURL(/#\/$/)
  profiles.delete('10000000-0000-0000-0000-000000000002')
  await page.evaluate(() => window.dispatchEvent(new Event('online')))
  await expect(page.getByLabel('Email', { exact: true })).toBeVisible()
  await expect(page.getByRole('status')).toContainText('Δεν βρέθηκε ενεργό προφίλ')
  expect(accountRequests).toEqual([])
})

test('membership refresh preserves cached coach access during a temporary server outage', async ({ page }) => {
  const { workout } = await mockAccount(page, 'coach', true, { active: true })
  await page.goto(`/#/workout/${workout.id}`)
  let checked = false
  await page.route('https://workout-lab-test.supabase.co/rest/v1/profiles*', async route => {
    checked = true
    await route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ message: 'Temporary outage' }) })
  })
  await page.evaluate(() => window.dispatchEvent(new Event('online')))
  await expect.poll(() => checked).toBe(true)
  await expect(page.getByTestId('panel-anna')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Διακοπή', exact: true })).toBeVisible()
  expect(await page.evaluate(() => Boolean(localStorage.getItem('wl-profile:10000000-0000-0000-0000-000000000001')))).toBe(true)
})

async function layout(page: Page) {
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
  await expect(page.locator('.calendar-day')).toHaveCount(7)
  for (const button of await page.locator('.calendar-week-toolbar, .calendar-week').getByRole('button').all()) {
    const box = await button.boundingBox(); if (box) expect(box.height).toBeGreaterThanOrEqual(44)
  }
  expect(await page.locator('.calendar-entry').evaluateAll(cards => cards.every(card => card.scrollWidth <= card.clientWidth + 1))).toBe(true)
  const viewport = page.viewportSize()!
  if (viewport.width === 1024) {
    await expect(page.locator('.sidebar')).toBeHidden()
    await expect(page.locator('.bottom-nav')).toBeVisible()
  }
}
async function add(page: Page, date: string, routine = 'day-2', time = '18:00', annaOnly = false) {
  await page.getByRole('button', { name: 'Νέα προπόνηση', exact: true }).click()
  const editor = page.getByRole('dialog', { name: 'Νέα προγραμματισμένη προπόνηση', exact: true })
  await editor.getByLabel('Προπόνηση', { exact: true }).selectOption(routine)
  await editor.getByLabel('Ημερομηνία', { exact: true }).fill(date)
  if (time) await editor.getByLabel('Ώρα έναρξης (προαιρετικά)', { exact: true }).fill(time)
  if (annaOnly) await editor.getByRole('checkbox', { name: 'Δήμητρα', exact: true }).uncheck()
  await editor.getByRole('button', { name: 'Αποθήκευση προγραμματισμού', exact: true }).click()
  await expect(editor).toHaveCount(0)
}

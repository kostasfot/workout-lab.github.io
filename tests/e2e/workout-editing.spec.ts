test('reps adjustments stay independent, respect limits and lock after recording', async ({ page }) => {
  await preview(page)
  const anna = page.getByTestId('panel-anna'), dimitra = page.getByTestId('panel-dimitra')
  const value = anna.getByLabel(/^Επαναλήψεις/), buttons = anna.locator('.value-increments')
  for (const button of await buttons.getByRole('button', { name: /^Μείωση/ }).all()) await expect(button).toBeDisabled()
  await clickAdjustment(anna, 'Αύξηση 5 επαναλήψεων Άννα Goblet Squats')
  await clickAdjustment(anna, 'Αύξηση 1 επαναλήψεων Άννα Goblet Squats', { clickCount: 2 })
  await expect(value).toHaveValue('7')
  await clickAdjustment(anna, 'Μείωση 5 επαναλήψεων Άννα Goblet Squats')
  await clickAdjustment(anna, 'Μείωση 1 επαναλήψεων Άννα Goblet Squats')
  await expect(value).toHaveValue('1')
  await expect(anna.getByRole('button', { name: 'Μείωση 1 επαναλήψεων Άννα Goblet Squats', exact: true })).toBeDisabled()
  await expect(dimitra.getByLabel(/^Επαναλήψεις/)).toHaveValue('')
  await value.fill('3595')
  await clickAdjustment(anna, 'Αύξηση 5 επαναλήψεων Άννα Goblet Squats')
  await expect(value).toHaveValue('3600')
  await buttons.getByRole('combobox').selectOption('1')
  await expect(anna.getByRole('button', { name: 'Αύξηση 1 επαναλήψεων Άννα Goblet Squats', exact: true })).toBeDisabled()
  await value.fill('10'); await anna.getByLabel(/^Βάρος/).fill('5')
  await anna.getByRole('button', { name: 'Καταγραφή', exact: true }).click()
  for (const button of await buttons.getByRole('button').all()) await expect(button).toBeDisabled()
  await expect(buttons.getByRole('combobox')).toBeDisabled()
  await page.reload(); await expect(value).toHaveValue('10')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})


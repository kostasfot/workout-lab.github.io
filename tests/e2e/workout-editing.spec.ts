test('starting another routine offers resume or confirmed replacement and syncs one empty active workout', async ({ page, context }) => {
  const { requests, remote, workout } = await mockAccount(page, 'coach', true, { active: true })
  // The production PWA precaches routes; the development server does not.
  await page.goto(`/#/workout/${workout.id}`)
  await expect(page.getByTestId('panel-anna')).toBeVisible()
  await page.goto('/#/')
  await page.getByRole('button', { name: 'Έναρξη Προπόνηση 2', exact: true }).click()
  const choice = page.getByRole('dialog', { name: 'Έτοιμες για προπόνηση;', exact: true })
  await expect(choice.getByLabel('Επιλογή προπόνησης').locator('option:checked')).toContainText('Προπόνηση 2')
  await expect(choice.getByRole('button', { name: 'Συνέχεια τρέχουσας', exact: true })).toBeVisible()
  await choice.getByRole('button', { name: 'Διακοπή και νέα προπόνηση', exact: true }).click()
  let confirmation = page.getByRole('dialog', { name: 'Διακοπή και νέα προπόνηση', exact: true })
  await confirmation.getByRole('button', { name: 'Ακύρωση', exact: true }).click()
  expect(remote.workouts[0].id).toBe(workout.id); expect(requests).toHaveLength(0)
  await context.setOffline(true)
  await choice.getByRole('button', { name: 'Διακοπή και νέα προπόνηση', exact: true }).click()
  confirmation = page.getByRole('dialog', { name: 'Διακοπή και νέα προπόνηση', exact: true })
  await confirmation.getByRole('button', { name: 'Διακοπή και έναρξη', exact: true }).click()
  await expect(page.getByTestId('panel-anna')).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Προπόνηση 2.', exact: true })).toBeVisible()
  await expect(page.getByTestId('panel-anna').getByLabel(/^Επαναλήψεις/)).toHaveValue('')
  await expect(page.getByTestId('panel-anna').getByRole('textbox')).toHaveValue('')
  expect(requests).toHaveLength(0)
  await context.setOffline(false); await synchronize(page)
  expect(requests.filter(r => r.endpoint === 'delete_record')).toHaveLength(1)
  expect(requests.filter(r => r.endpoint === 'save_record' && r.kind === 'workout')).toHaveLength(1)
  expect(remote.workouts).toHaveLength(1)
  expect(remote.workouts[0].id).not.toBe(workout.id)
  expect(remote.workouts[0].status).toBe('active')
  expect(remote.workouts[0].results).toEqual({}); expect(remote.notes).toEqual([])
  await page.goto('/#/'); await page.reload()
  await page.getByRole('button', { name: 'Συνέχεια προπόνησης', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Προπόνηση 2.', exact: true })).toBeVisible()
  await page.goto('/#/history')
  await expect(page.getByText('Το ιστορικό σας ξεκινά εδώ.', { exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})
